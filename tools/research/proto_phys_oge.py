def _pick_distinct(rng, keys, k, val, pool_vals, nbad):
    """k ключей с различными значениями val + nbad «лишних» значений, не совпадающих ни с одним выбранным."""
    for _ in range(100):
        L = pick(rng, keys, k)
        vals = [val(x) for x in L]
        if len(set(vals)) < k:
            continue
        pool = sorted(set(pool_vals) - set(vals))
        if len(pool) < nbad:
            continue
        return L, vals, pick(rng, pool, nbad)
    raise Retry


