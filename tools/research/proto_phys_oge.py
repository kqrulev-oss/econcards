def _gap_card(pid, rng, text, right_words, decoys, p, e):
    """right_words — слова для (А)…(Г) по порядку; decoys — лишние слова. Список перемешивается."""
    words = shuffled(rng, right_words + decoys)
    left = [f'({LET[i]})' for i in range(len(right_words))]
    a = {LET[i]: str(words.index(w) + 1) for i, w in enumerate(right_words)}
    p = dict(p, words=words)
    return pcard(pid, f'{HEAD4}\n{text}\nСписок слов и словосочетаний приведён во втором столбце.{TAIL4}', a, e,
                 k='match', o=match_opts(left, words), p=p)


def _ans_by_words(p, need):
    return {LET[i]: str(p['words'].index(w) + 1) for i, w in enumerate(need)}


