SUP = str.maketrans('-0123456789', '⁻⁰¹²³⁴⁵⁶⁷⁸⁹')
CH = {'1': 'увеличится', '2': 'уменьшится', '3': 'не изменится'}
CH_R = [CH['1'], CH['2'], CH['3']]


def sci(m, e):
    """3·10⁸"""
    return f'{ru(m)}·10{str(e).translate(SUP)}'


def raz(x):
    x = Fr(x)
    if x.denominator != 1:
        return 'раза'
    n = x.numerator
    return 'раза' if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14) else 'раз'


VERB = {'m': ('увеличился', 'уменьшился', 'не изменился'), 'f': ('увеличилась', 'уменьшилась', 'не изменилась'),
        'n': ('увеличилось', 'уменьшилось', 'не изменилось'), 'p': ('увеличились', 'уменьшились', 'не изменились')}
VERB_F = {'m': ('увеличится', 'уменьшится', 'не изменится'), 'f': ('увеличится', 'уменьшится', 'не изменится'),
          'n': ('увеличится', 'уменьшится', 'не изменится'), 'p': ('увеличатся', 'уменьшатся', 'не изменятся')}


def rtxt(r, g='f', fut=False):
    """Отношение «стало/было» → «увеличилась в 2 раза» / «уменьшилась в 4 раза» / «не изменилась»."""
    v = (VERB_F if fut else VERB)[g]
    r = Fr(r)
    if r == 1:
        return v[2]
    if r > 1:
        return f'{v[0]} в {ru(r)} {raz(r)}'
    return f'{v[1]} в {ru(1 / r)} {raz(1 / r)}'


def near(a, b, tol=1e-9):
    a, b = float(a), float(b)
    return abs(a - b) <= tol * max(1.0, abs(a), abs(b))


def chg(a, b):
    """Код изменения величины a → b: 1 — увеличится, 2 — уменьшится, 3 — не изменится."""
    if near(a, b):
        return '3'
    return '1' if b > a else '2'


def fr(x):
    return str(Fr(x))


def rnd(x, dec):
    """Округление ответа части 2 до dec знаков; если значение у самой границы округления — Retry
    (чтобы независимый пересчёт в solve не разошёлся в последнем знаке)."""
    y = float(x) * 10 ** dec
    if abs(y - math.floor(y) - 0.5) < 1e-4:
        raise Retry
    return fmt(float(x), dec)


def many_card(pid, rng, q, items, p, head='', kmin=2, kmax=3, n=5, fixed=False):
    """«Выберите все верные»: items — [(текст, spec, истина, пояснение)]. Берём n утверждений, из них kmin..kmax верных.
    spec пишется в p['claims'] — по нему solve() независимо решает, верно ли утверждение."""
    if fixed:
        ch = list(items)
    else:
        tr = [x for x in items if x[2]]
        fl = [x for x in items if not x[2]]
        k = rng.randint(kmin, kmax)
        if len(tr) < k or len(fl) < n - k:
            raise Retry
        ch = rng.sample(tr, k) + rng.sample(fl, n - k)
        rng.shuffle(ch)
    texts = [c[0] for c in ch]
    if len(set(texts)) != len(texts):
        raise Retry
    a = [str(i + 1) for i, c in enumerate(ch) if c[2]]
    if not (2 <= len(a) <= 3):
        raise Retry
    p = dict(p, claims=[c[1] for c in ch])
    e = (head + ' ' if head else '') + ' '.join(f'{i + 1}) {"верно" if c[2] else "неверно"}: {c[3]}' for i, c in enumerate(ch)) + \
        f' Ответ: {"".join(a)}.'
    return pcard(pid, q, a, e, k='many', o=opts(texts), p=p)


def eval_claim(m, s):
    """Истинность утверждения-спецификации s по независимой модели m (dict величин)."""
    t = s['t']
    if t == 'v':          # значение величины
        return near(m[s['q']], Fr(s['v']))
    if t == 'is':         # качественное свойство
        return m[s['q']] == s['v']
    if t == 'cmp':        # сравнение двух величин: '>', '<', '='
        a, b = m[s['q']], m[s['q2']]
        return {'>': a > b and not near(a, b), '<': a < b and not near(a, b), '=': near(a, b)}[s['v']]
    if t == 'r':          # отношение «после/до»
        return near(m[s['q']], Fr(s['v']))
    raise ValueError(t)


def solve_many(model):
    def solve(p):
        m = model(p)
        return [str(i + 1) for i, s in enumerate(p['claims']) if eval_claim(m, s)]
    return solve


def change_card(pid, q, names, ans, e, p, extra_right=None):
    o = match_opts(names, CH_R)
    return pcard(pid, q, ans, e, k='match', o=o, p=p)


def fid(fmt_, style, level, t, scale, trap, kes, score):
    return dict(answer_format=fmt_, style=style, level=level, time_min=t, scale=scale, trap=trap, kes=kes, score=score)


