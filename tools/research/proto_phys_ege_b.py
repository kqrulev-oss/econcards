LG_SHAPES = {'q': 'заряд левой обкладки конденсатора', 'i': 'модуль силы тока в катушке', 'WC': 'энергия электрического поля конденсатора',
             'WL': 'энергия магнитного поля катушки', 'U': 'модуль напряжения на конденсаторе'}


def _lg_values(key):
    """Табличные значения (в долях максимума) в моменты 0, T/8, …, T для каждой величины — генератор (по таблице)."""
    return {'q': ['1', '0,71', '0', '−0,71', '−1', '−0,71', '0', '0,71', '1'],
            'i': ['0', '0,71', '1', '0,71', '0', '0,71', '1', '0,71', '0'],
            'WC': ['1', '0,5', '0', '0,5', '1', '0,5', '0', '0,5', '1'],
            'WL': ['0', '0,5', '1', '0,5', '0', '0,5', '1', '0,5', '0'],
            'U': ['1', '0,71', '0', '0,71', '1', '0,71', '0', '0,71', '1']}[key]


def _solve_lg(p):
    def prof(key):
        out = []
        for j in range(9):
            ph = 2 * math.pi * j / 8
            v = {'q': math.cos(ph), 'i': abs(math.sin(ph)), 'WC': math.cos(ph) ** 2, 'WL': math.sin(ph) ** 2, 'U': abs(math.cos(ph))}[key]
            out.append(round(v, 2))
        return out
    res = {}
    for L, tab in (('А', p['ta']), ('Б', p['tb'])):
        vals = [float(x.replace('−', '-').replace(',', '.')) for x in tab]
        hits = [rid for rid, key in p['right'].items() if all(abs(a - b) < 0.011 for a, b in zip(prof(key), vals))]
        res[L] = hits[0] if len(hits) == 1 else 'нет'
    return res


