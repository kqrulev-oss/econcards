def _coul_model(p):
    q1, q2, r = p['q1'], p['q2'], p['r']
    k = 9 * 10 ** 9
    F = Fr(k) * abs(q1 * q2) * Fr(1, 10 ** 18) / (Fr(r, 100) ** 2)          # Н
    qm = Fr(q1 + q2, 2)
    F2 = Fr(k) * qm * qm * Fr(1, 10 ** 18) / (Fr(r, 100) ** 2)
    E1 = Fr(k) * abs(q1) * Fr(1, 10 ** 9) / (Fr(r, 100) ** 2)                # В/м
    return {'F': F * 10 ** 6, 'F2': F2 * 10 ** 6, 'E1': E1 / 1000, 'kind': 'отт' if q1 * q2 > 0 else 'прит',
            'n3': 'равны', 'rr': Fr(1, p['m'] ** 2)}


