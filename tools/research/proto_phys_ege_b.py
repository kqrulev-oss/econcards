# ---------- 14-circuit: источник с внутренним сопротивлением и два резистора

CIRC_PLOT = [('аккумулятор', 'м'), ('гальванический элемент', 'м'), ('батарейка', 'ж'), ('лабораторный источник тока', 'м')]
LOADS = [('резистор', 'резистора', 'резисторе'), ('нагревательный элемент', 'нагревательного элемента', 'нагревательном элементе'),
         ('проволочный реостат', 'реостата', 'реостате')]


def _circ_model(p):
    E, r, R1, R2 = Fr(p['E']), Fr(p['r']), Fr(p['R1']), Fr(p['R2'])
    if p['par']:
        G = 1 / R1 + 1 / R2
        I = E / (r + 1 / G)
        U = E - I * r
        I1, I2, U1, U2 = U / R1, U / R2, U, U
    else:
        I = E / (R1 + R2 + r)
        I1 = I2 = I
        U1, U2 = I * R1, I * R2
        U = U1 + U2
