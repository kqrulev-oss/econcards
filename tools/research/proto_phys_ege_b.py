def _cap_model(p):
    """Независимо: абсолютные величины до и после (ε₀ = 1)."""
    def st(eps, S, d):
        C = Fr(eps) * Fr(S) / Fr(d)
        if p['mode'] == 'src':
            U = Fr(1)
            q = C * U
        else:
            q = Fr(1)
            U = q / C
        return {'C': C, 'q': q, 'U': U, 'E': U / Fr(d), 'W': q * U / 2}
    a = st(1, 1, 1)
    eps, S, d = Fr(1), Fr(1), Fr(1)
    if p['what'] == 'd':
        d = Fr(p['k'])
    elif p['what'] == 'S':
        S = Fr(p['k'])
    else:
        eps = Fr(p['k'])
    b = st(eps, S, d)
    return {k: b[k] / a[k] for k in a}


