def g14_cap(rng):
    mode = rng.choice(['src', 'iso'])
    what = rng.choice(['d', 'd', 'S', 'eps'])
    if what == 'eps':
        k = Fr(rng.choice([2, 3, 4, 5, 6, 7]))
        how = rng.choice([f'Зазор между обкладками целиком заполняют пластиной диэлектрика с диэлектрической проницаемостью ε = {k}',
                          f'Пространство между пластинами полностью заполняют жидким диэлектриком (ε = {k})'])
    else:
        k = Fr(rng.choice([2, 3, 4])) ** rng.choice([1, -1])
        noun = 'расстояние между обкладками' if what == 'd' else 'площадь перекрытия пластин'
        how = f'Затем {noun} {"увеличивают" if k > 1 else "уменьшают"} в {ru(max(k, 1 / k))} {raz(max(k, 1 / k))}'
        how = how[0].upper() + how[1:]
    head = f'{rng.choice(CAP_PLOT)} ' + ('подключён к источнику постоянного напряжения и всё время остаётся подключённым к нему.'
                                          if mode == 'src' else 'зарядили от источника постоянного напряжения и отключили от него.')
    # генератор: правила пропорциональности (в solve — расчёт абсолютных величин)
    rC = k if what in ('S', 'eps') else 1 / k
    kd = k if what == 'd' else Fr(1)
    if mode == 'src':
        r = {'C': rC, 'q': rC, 'U': Fr(1), 'E': 1 / kd, 'W': rC}
    else:
        r = {'C': rC, 'q': Fr(1), 'U': 1 / rC, 'E': 1 / rC / kd, 'W': 1 / rC}
    why = {'C': f'C ∝ εS/d, {rtxt(rC)}', 'q': 'q = CU' + (', U = const' if mode == 'src' else ' сохраняется: источник отключён'),
           'U': 'U = q/C' if mode == 'iso' else 'U задаёт источник', 'E': 'E = U/d', 'W': 'W = qU/2'}
    ntrue = rng.choice([2, 3])
    true_keys = set(rng.sample([x[0] for x in CAP_Q], ntrue))
    items = []
    for key, name, g in rng.sample(CAP_Q, 5):
        rv = r[key]
        if key in true_keys:
            val = rv
