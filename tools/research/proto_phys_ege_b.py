def _lor_model(p):
    m0, q0 = PART[p['part']]
    def st(m, q, v, B):
        return {'R': Fr(m) * v / (q * B), 'T': Fr(m) / (q * B), 'F': Fr(q) * v * B}
    a = st(m0, q0, 1, 1)
    out = {'A': 'ноль', 'Ek': 'пост', 'dir': 'перп'}
    kv, kb = Fr(p['kv']), Fr(p['kb'])
    b = st(m0, q0, kv, 1)
    c = st(m0, q0, 1, kb)
    m1, q1 = PART[p['other']]
    d = st(m1, q1, 1, 1)
    for k in a:
        out[k + '_v'] = b[k] / a[k]
        out[k + '_B'] = c[k] / a[k]
        out[k + '_x'] = d[k] / a[k]
    return out


