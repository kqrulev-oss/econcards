# ---------- 15-formula: соответствие «величина — формула» (цепь, частица, контур)

def _feval(expr, env):
    return eval(expr, {'sqrt': math.sqrt, 'pi': math.pi}, dict(env))


def _solve_formula(p):
    """Для каждой величины ищем формулу, значение которой совпадает с эталонной величиной на нескольких наборах чисел."""
    out = {}
    for L, qexpr in (('А', p['qa']), ('Б', p['qb'])):
        hit = []
        for rid, fexpr in p['forms'].items():
            ok = True
            for env in p['envs']:
                if not near(_feval(fexpr, env), _feval(qexpr, env), 1e-9):
                    ok = False
                    break
            if ok:
                hit.append(rid)
        out[L] = hit[0] if len(hit) == 1 else 'нет'
    return out


def formula_card(pid, rng, q, quants, forms_pool, ref, envs):
    """quants: [(название, ключ)]; forms_pool: {ключ: (текст формулы, python-выражение)}; ref: {ключ: эталонное выражение (иначе записанное)}."""
    (na, ka), (nb, kb) = rng.sample(quants, 2)
    others = [k for k in forms_pool if k not in (ka, kb)]
    chosen = [ka, kb] + rng.sample(others, 2)
    rng.shuffle(chosen)
    texts = [forms_pool[k][0] for k in chosen]
    if len(set(texts)) < 4:
        raise Retry
    rids = '1234'
    forms = {rids[i]: forms_pool[k][1] for i, k in enumerate(chosen)}
    ans = {'А': rids[chosen.index(ka)], 'Б': rids[chosen.index(kb)]}
    o = match_opts([na, nb], texts)
    e = f'{na[0].upper() + na[1:]}: {forms_pool[ka][0]}; {nb}: {forms_pool[kb][0]}. Ответ: {ans["А"]}{ans["Б"]}.'
    p = {'qa': ref[ka], 'qb': ref[kb], 'forms': forms, 'envs': envs}
    return pcard(pid, q, ans, e, k='match', o=o, p=p)


