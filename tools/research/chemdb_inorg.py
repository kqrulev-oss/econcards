def _auto_ox(f):
    from pc_core import parse_formula
    comp = parse_formula(f)
    els = list(comp)
    if len(els) == 1:
        return {els[0]: 0}
    ox = {}
    for e in els:
        if e in _FIXED:
            ox[e] = _FIXED[e]
    if 'O' in comp and 'O' not in ox:
        ox['O'] = -2
    if 'H' in comp and 'H' not in ox:
        ox['H'] = 1
    rest = [e for e in els if e not in ox]
    if len(rest) != 1:
        return None
    e = rest[0]
    s = sum(ox[x] * comp[x] for x in ox)
    v = Fr(-s, comp[e])
    return dict(ox, **{e: int(v) if v.denominator == 1 else v})


