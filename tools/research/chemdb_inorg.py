_RKEYS = set()


def R(lhs, rhs, type=(), cond='', sign='', tags=(), src='школьный курс', **kw):
    key = (tuple(sorted(lhs)), tuple(sorted(rhs)), cond)
    if key in _RKEYS:
        return None
    _RKEYS.add(key)
    row = dict(lhs=list(lhs), rhs=list(rhs), type=list(type), cond=cond)
    if sign:
        row['sign'] = sign
    if tags:
        row['tags'] = list(tags)
    row['src'] = src
    row.update({k: v for k, v in kw.items() if v is not None})
    REACTIONS.append(row)
    return row


