def _cat_metal(f):
    s = _BY[f]
    if f in ('NaOH', 'KOH'):
        return f[:-2]
    if s['cls'] == 'кислота':
        return 'H'
    ion = s.get('ion')
    if ion:
        return CAT[ion['cat']][3] if ion['cat'] != 'NH4' else 'NH4'
    return re.match(r'[A-Z][a-z]?', f).group()


def _anion(f):
    s = _BY[f]
    if f in ('NaOH', 'KOH'):
        return 'OH'
    if s['cls'] == 'кислота':
        return AN_OF_ACID[f]
    ion = s.get('ion')
    if ion:
        return ion['an']
    return {'NiSO4': 'SO4', 'NiCl2': 'Cl', 'SnCl2': 'Cl', 'CrCl2': 'Cl'}[f]


def electrolysis_products(f, melt=False):
    """Продукты на инертных электродах: (катод, анод) — списки формул."""
    m, an = _cat_metal(f), _anion(f)
    if melt:
        cat = [m]
        anode = {'Cl': ['Cl2'], 'Br': ['Br2'], 'I': ['I2'], 'F': ['F2'], 'OH': ['O2', 'H2O']}.get(an)
        return cat, anode
    if m in ('H',):
        cat = ['H2']
    elif m in ('Ag', 'Cu', 'Hg', 'Au', 'Pt'):
        cat = [m]
    elif m in _MID:
        cat = [m, 'H2']
    else:
        cat = ['H2']
    anode = {'Cl': ['Cl2'], 'Br': ['Br2'], 'I': ['I2'], 'S': ['S'], 'CH3COO': ['C2H6', 'CO2']}.get(an, ['O2'])
    return cat, anode


