def _selfcheck():
    import sys
    import os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from pc_core import parse_formula, balance
    probs = []
    for s in SUBSTANCES:
        try:
            parse_formula(s['f'])
        except Exception as ex:  # noqa: BLE001
            probs.append(f'формула {s["f"]}: {ex}')
        o = s.get('ox')
        if o is None:
            continue
        comp = parse_formula(s['f'])
        if any(isinstance(v, list) for v in o.values()):
            continue
        tot = sum(Fr(o.get(e, 0)) * n for e, n in comp.items())
        if tot != 0 or set(o) != set(comp):
            probs.append(f'ст. ок. {s["f"]}: сумма {tot}, {o}')
    seen = set()
    for r in REACTIONS:
        for f in r['lhs'] + r['rhs']:
            if f not in _BY:
                probs.append(f'нет вещества {f} в {r["lhs"]}→{r["rhs"]}')
        try:
            balance(r['lhs'], r['rhs'])
        except Exception as ex:  # noqa: BLE001
            probs.append(f'{r["lhs"]}→{r["rhs"]} [{r["cond"]}]: {ex}')
    # «не реагирует» не должно противоречить реакциям
    for x, fx, y, fy, why in NO_REACTION:
        for f in (x, y):
            if f not in _BY:
                probs.append(f'NO_REACTION: нет вещества {f}')
        for r in REACTIONS:
            if x in r['lhs'] and y in r['lhs'] and x != y and set(r['lhs']) - {x, y} <= {'H2O'}:
                form = r.get('form', {})
                cf = r.get('cond', '')
                ok_x = (not fx) or form.get(x, fx) == fx or (fx == 'р-р' and form.get(x) in (None, 'разб.', 'р-р'))
                ok_y = (not fy) or form.get(y, fy) == fy or (fy == 'р-р' and form.get(y) in (None, 'разб.', 'р-р'))
                if 'сплавление' in cf or 'расплав' in cf:
                    continue
                if fx == 'хол.' or fy == 'хол.':
                    if 't' in cf:
                        continue
                if (fx == 'конц.' or fy == 'конц.') and 't' in cf:
                    continue
                if ok_x and ok_y:
                    probs.append(f'противоречие: {x}({fx}) + {y}({fy}) «{why}», но есть {r["lhs"]}→{r["rhs"]} [{cf}]')
                    break
    return probs


