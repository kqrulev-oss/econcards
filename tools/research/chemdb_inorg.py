def _add_salt(ck, ak, sub='средняя соль', sol=None, **kw):
    f = salt_formula(ck, ak)
    c, a = CAT[ck], AN[ak]
    ox = {c[3]: c[4]}
    if ck == 'NH4':
        ox['H'] = 1
    for el, v in a[3].items():
        if el in ox and ox[el] != v:
            ox[el] = sorted({ox[el], v}) if not isinstance(ox[el], list) else sorted(set(ox[el]) | {v})
        else:
            ox[el] = v
    if ak == 'CH3COO':
        ox['C'] = [-3, 3]
    color = _PREC_COLOR.get(f) or _CAT_COLOR.get(ck) or 'белый'
    S(f, salt_name(ck, ak), 'соль', sub, sol=sol, color=color, state='тв', ox=ox,
      ion={'cat': ck, 'an': ak, 'n': [AN[ak][1] // _g(c[1], a[1]), c[1] // _g(c[1], a[1])]},
      trivial=TRIVIAL.get(f, []), lattice='ионная', **kw)
    return f


