def _grp(part, n):
    """Часть формулы с индексом: ('NH4', 2) → '(NH4)2'; ('Na', 2) → 'Na2'."""
    if n == 1:
        return part
    simple = re.fullmatch(r'[A-Z][a-z]?', part) is not None
    return f'{part}{n}' if simple else f'({part}){n}'


def salt_formula(ck, ak):
    c, a = CAT[ck], AN[ak]
    from math import gcd
    g = gcd(c[1], a[1])
    nc, na = a[1] // g, c[1] // g
    if ak == 'CH3COO':   # ацетаты пишем как в ЕГЭ: CH3COONa, (CH3COO)2Ca
        return (f'(CH3COO){na}' if na > 1 else 'CH3COO') + _grp(c[0], nc)
    return _grp(c[0], nc) + _grp(a[0], na)


def salt_name(ck, ak):
    return f'{AN[ak][2]} {CAT[ck][2]}'


