def _solve_newton_num(p):
    k = p['kind']
    m = Fr(p['m'])
    if k == 'dv':
        return A(m * abs(Fr(p['v2']) - Fr(p['v1'])) / Fr(p['t']))
    if k == 'two':
        F = Fr(p['F1']) + Fr(p['F2']) * (1 if p['same'] else -1)
        return A(abs(F) / m)
    if k == 'vfin':
        return A(Fr(p['F']) / m * Fr(p['t']))
    if k == 'table':
        vs = [Fr(v) for v in p['vs']]
        return A(m * abs(vs[-1] - vs[0]) / (p['ts'][-1] - p['ts'][0]))
    raise ValueError(k)


