def _solve_hooke(p):
    k = p['kind']
    if k == 'prop':
        return A(Fr(p['x1']) * Fr(p['F2']) / Fr(p['F1']) if p['ask'] == 'x' else Fr(p['F1']) * Fr(p['x2']) / Fr(p['x1']))
    if k == 'mass':
        return A(Fr(p['m']) * G / (Fr(p['x']) / 100))
    if k == 'table':
        Fs, xs = [Fr(v) for v in p['Fs']], [Fr(v) for v in p['xs']]
        return A((Fs[-1] - Fs[0]) / ((xs[-1] - xs[0]) / 100))
    if k == 'two':
        return A(Fr(p['k1']) * Fr(p['x1']) / Fr(p['k2']))
    raise ValueError(k)


SPRINGS = ['пружина динамометра', 'пружина амортизатора', 'пружина эспандера', 'лёгкая пружина', 'пружина весов', 'резиновый жгут']


