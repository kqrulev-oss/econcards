def g_newton_num(rng):
    nom, acc, gen, ms = pick(rng, N2N)
    m = Fr(pick(rng, ms))
    kind = pick(rng, ['dv', 'two', 'vfin', 'table'])
    if kind == 'dv':
        v1 = pick(rng, [0, 1, 2, 4, 5, 10])
        v2 = v1 + pick(rng, [-4, -2, -1, 1, 2, 3, 4, 5, 10])
        if v2 < 0:
            raise Retry
        t = pick(rng, [1, 2, 4, 5, 10, 20])
        if m > 100 and abs(v2 - v1) < 2:
            raise Retry
        p = {'kind': kind, 'm': str(m), 'v1': v1, 'v2': v2, 't': t}
        ans = _solve_newton_num(p)
        q = (f'{nom} массой {Q(m)} кг движется прямолинейно. За {t} с модуль скорости {gen} равномерно изменился от {v1} до {v2} м/с. '
             f'Чему равен модуль равнодействующей сил, действовавших на {acc} в этот промежуток времени?' + ans_line('Н'))
        e = f'a = |Δυ|/Δt = {abs(v2 - v1)}/{t} м/с²; F = ma = {Q(m)}·{Q(Fr(abs(v2 - v1), t))} = {ans} Н.'
        wrong = [W(m * v2 / t), W(m * abs(v2 - v1) * t), W(m * (v1 + v2) / t)]
    elif kind == 'two':
        F1 = pick(rng, [2, 3, 4, 5, 6, 8, 10, 12, 15, 20]) * (m if m >= 1 else 1)
        F2 = pick(rng, [1, 2, 3, 4, 5, 6]) * (m if m >= 1 else 1)
        same = rng.random() < 0.4
        if not same and F1 == F2:
            raise Retry
        F1, F2 = Fr(F1) * (1 if m >= 1 else Fr(1, 10)), Fr(F2) * (1 if m >= 1 else Fr(1, 10))
        p = {'kind': kind, 'm': str(m), 'F1': str(F1), 'F2': str(F2), 'same': same}
        ans = _solve_newton_num(p)
        how = 'направленные в одну сторону' if same else 'направленные в противоположные стороны'
        q = (f'На {acc} массой {Q(m)} кг, движущ{"ую" if acc[-1] in "уы" else "ий"}ся по прямой, действуют две горизонтальные силы {Q(F1)} Н и {Q(F2)} Н, {how} вдоль этой прямой; '
             f'остальные силы скомпенсированы. Чему равен модуль ускорения {gen}?' + ans_line('м/с²'))
