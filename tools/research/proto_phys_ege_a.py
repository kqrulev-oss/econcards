def sign_code(a, b, tol=1e-9):
    if math.isclose(a, b, rel_tol=tol, abs_tol=1e-15):
        return '3'
    return '1' if b > a else '2'


def num_card(pid, q, ans, e, p, wrong):
    return pcard(pid, q, ans, e, k='num', p=p, wrong=[w for w in wrong if w is not None])


def W(x, dec=3):
    """Неверный ответ-строка (или None)."""
    try:
        x = Fr(x)
    except (TypeError, ValueError, ZeroDivisionError):
        return None
    return fmt(x, dec)


def many_card(pid, rng, q, pool, p, lo=2, hi=3, tail='Выберите все верные утверждения на основании анализа представленных данных.'):
    """pool: [(текст, истина, спец для solve, пояснение)] — выбирает 5 утверждений, из них верных от lo до hi.
    В p['st'] кладутся спецификации выбранных утверждений: solve() сам решает, какие из них верны."""
    tr = [x for x in pool if x[1]]
    fl = [x for x in pool if not x[1]]
    k = rng.randint(lo, hi)
    if len(tr) < k or len(fl) < 5 - k:
        raise Retry
    chosen = rng.sample(tr, k) + rng.sample(fl, 5 - k)
    rng.shuffle(chosen)
    texts = [c[0] for c in chosen]
    if len(set(texts)) != 5:
        raise Retry
    ans = [str(i + 1) for i, c in enumerate(chosen) if c[1]]
    p = dict(p, st=[c[2] for c in chosen])
    why = '; '.join(f'{i + 1}) {"верно" if c[1] else "неверно"}' + (f': {c[3]}' if len(c) > 3 and c[3] else '')
                    for i, c in enumerate(chosen))
    e = why + '. Ответ: ' + ''.join(ans) + '.'
    return pcard(pid, q + '\n' + tail, ans, e, k='many', o=opts(texts), p=p)


def change_card(pid, q, names, codes, e, p, present=False):
    o = match_opts(names, CH_P if present else CH)
    a = {'АБВГ'[i]: c for i, c in enumerate(codes)}
    return pcard(pid, q + '\nДля каждой величины определите соответствующий характер изменения.', a, e, k='match', o=o, p=p)


def term(c, s, first=False):
    """Слагаемое многочлена для записи закона движения: term(-2,'t') → ' − 2t'."""
    c = Fr(c)
    if c == 0:
        return ''
    mag = '' if abs(c) == 1 and s else Q(abs(c))
    sg = ('−' if c < 0 else '') if first else (' − ' if c < 0 else ' + ')
    return sg + mag + s


