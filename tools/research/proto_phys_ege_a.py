def g_vt_path(rng):
    body = pick(rng, VT_BODIES)
    dt, knots, ts, vs = _vt_profile(rng, body)
    n = len(ts) - 1
    i = pick(rng, [0, 0, rng.randrange(0, n)])
    j = rng.randrange(i + 1, n + 1)
    if j - i < 2:
        raise Retry
    neg = any(v < 0 for v in vs[i:j + 1]) and any(v > 0 for v in vs[i:j + 1])
    what = 'disp' if neg and rng.random() < 0.4 else 'path'
