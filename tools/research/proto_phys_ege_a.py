def g_vt_accel(rng):
    body = pick(rng, VT_BODIES)
    dt, knots, ts, vs = _vt_profile(rng, body)
    seg = rng.randrange(3)
    t0, t1 = knots[seg][0], knots[seg + 1][0]
    if t1 - t0 >= 2 and rng.random() < 0.4:
        a0 = rng.randrange(t0, t1)
        b0 = rng.randrange(a0 + 1, t1 + 1)
    else:
        a0, b0 = t0, t1
    T1, T2 = a0 * dt, b0 * dt
    ax = (vs[b0] - vs[a0]) / (T2 - T1)
    if ax == 0:
        raise Retry
    ans = A(ax)
    q = (f'{body[0]} Зависимость проекции υx скорости {body[1]} от времени t представлена в таблице '
         f'(между указанными моментами проекция скорости изменялась равномерно).\n'
         + table([('t, с', ts), ('υx, м/с', vs)])
         + f'\nЧему равна проекция ax ускорения {body[1]} на промежутке времени {Q(T1)}–{Q(T2)} с?' + ans_line('м/с²', sign=True))
    e = f'На этом участке ax = Δυx/Δt = ({Q(vs[b0])} − ({Q(vs[a0])}))/({Q(T2)} − {Q(T1)}) = {ans} м/с².'
    wrong = [W(-ax), W(vs[b0] / T2) if T2 else None, W((vs[b0] - vs[a0]) * (T2 - T1))]
    return num_card('ph-ege-01-vt-accel', q, ans, e, {'ts': ts, 'vs': [str(v) for v in vs], 't1': T1, 't2': T2}, wrong)


def _solve_vt_path(p):
    ts, vs = p['ts'], [Fr(x) for x in p['vs']]
    i, j = ts.index(p['t1']), ts.index(p['t2'])
    s, d = Fr(0), Fr(0)
    for k in range(i, j):
        h = Fr(ts[k + 1] - ts[k])
        a, b = vs[k], vs[k + 1]
        d += (a + b) / 2 * h
        s += abs(a + b) / 2 * h if a * b >= 0 else (a * a + b * b) / (2 * abs(b - a)) * h
    return A(abs(d) if p['what'] == 'disp' else s)


