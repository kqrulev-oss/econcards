def _solve_uniacc(p):
    v0, a, t, w = Fr(p['v0']), Fr(p['a']), Fr(p['t']), p['what']
    if w == 's':
        return A((2 * v0 + a * t) * t / 2)
    if w == 'v':
        return A(v0 + a * t)
    if w == 'a':
        return A(abs(a))
    if w == 'brake':
        return A(v0 * v0 / (2 * abs(a)))
    if w == 'nth':
        n = int(t)
        return A((v0 * n + a * n * n / 2) - (v0 * (n - 1) + a * (n - 1) ** 2 / 2))
    raise ValueError(w)


