def _solve_uniform(p):
    ts, xa, xb = p['ts'], [Fr(x) for x in p['xa']], [Fr(x) for x in p['xb']]
    va = (xa[-1] - xa[0]) / (ts[-1] - ts[0])
    vb = (xb[-1] - xb[0]) / (ts[-1] - ts[0])
    ask = p['ask']
    if ask == 'meet':
        return A((xb[0] - xa[0]) / (va - vb))
    if ask == 'dist':
        t = p['t']
        return A(abs(xa[0] + va * t - xb[0] - vb * t))
    if ask == 'vrel':
        return A(abs(va - vb))
    return A(abs(va) / abs(vb))


