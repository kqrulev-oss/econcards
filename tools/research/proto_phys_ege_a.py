        how = pick(rng, [('разгоняясь при движении вверх', True), ('тормозя при движении вниз', True), ('разгоняясь при движении вниз', False), ('тормозя при движении вверх', False)])
        up = how[1]
        p = {'kind': kind, 'm': m, 'a': str(a), 'up': up}
        ans = _solve_weight(p)
        q = (who[0].format(m=m) + f' на полу кабины лифта. Лифт движется, {how[0]}, с ускорением, модуль которого {Q(a)} м/с². '
             f'С какой силой {who[1]}?'.replace('давит, т. е. каковы', 'давит, т. е. каковы') + ans_line('Н'))
        q = q.replace('на весах на полу кабины', 'на весах в кабине')
        e = f'Ускорение направлено {"вверх" if up else "вниз"}: N {"−" if up else "+"} ... ⇒ P = N = m(g {"+" if up else "−"} a) = {m}·{Q(G + a if up else G - a)} = {ans} Н.'
        e = f'Ускорение направлено {"вверх" if up else "вниз"}, поэтому P = N = m(g {"+" if up else "−"} a) = {m}·{Q(G + a if up else G - a)} = {ans} Н.'
