def _solve_relative(p):
    k = p['kind']
    if k == 'meet':
        return A(Fr(p['d0'] - p['d1'], p['t']) - Fr(p['v1']))
    if k == 'catch':
        return A(Fr(p['v1']) + Fr(p['d0'] - p['d1'], p['t']))
    if k == 'river':
        vd, vu = Fr(p['L']) / Fr(p['td']), Fr(p['L']) / Fr(p['tu'])
        return A((vd - vu) / 2 if p['ask'] == 'river' else (vd + vu) / 2)
    if k == 'escal':
        return A(1 / (Fr(1, p['t1']) + Fr(1, p['t2'])))
    raise ValueError(k)


