def _solve_freefall(p):
    w = p['what']
    if w == 'h_t':
        return A(G * Fr(p['t']) ** 2 / 2)
    if w == 'v_h':
        return A(Fr(round(math.sqrt(2 * G * Fr(p['h'])))))
    if w == 'hmax':
        return A(Fr(p['v0']) ** 2 / (2 * G))
    if w == 'tup':
        return A(2 * Fr(p['v0']) / G)
    if w == 'v_t':
        return A(abs(Fr(p['v0']) - G * Fr(p['t'])))
    n = p['t']
    return A(Fr(G * n * n, 2) - Fr(G * (n - 1) ** 2, 2))


