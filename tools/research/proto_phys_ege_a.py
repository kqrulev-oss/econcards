def _solve_circle(p):
    w = p['what']
    if w == 'a':
        return A(Fr(p['v']) ** 2 / Fr(p['R']))
    if w == 'v':
        x = Fr(p['a']) * Fr(p['R'])
        r = math.isqrt(int(x))
        return A(r) if r * r == x else 'нет'
