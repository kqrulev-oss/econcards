def A(x, dec=2):
    """Ответ части 1: конечная дробь с ≤ dec знаками, иначе новая попытка."""
    s = exact(Fr(x), dec)
    if s is None:
        raise Retry
    return s


def Q(x):
    """Число для условия (дробь → «2,5», минус типографский)."""
    return ru(Fr(x))


def ok_dec(x, dec=2):
    return exact(Fr(x), dec) is not None


def pick(rng, xs):
    return xs[rng.randrange(len(xs))]


def table(rows):
    """rows: [(заголовок, [значения])] → строки таблицы «заголовок | a | b | c»."""
    return '\n'.join(f'{h} | ' + ' | '.join(v if isinstance(v, str) else Q(v) for v in vals) for h, vals in rows)


def raz(k):
    """«в 2 раза», «в 5 раз», «в 1,5 раза»."""
    k = Fr(k)
    if k.denominator != 1:
        return f'{Q(k)} раза'
    n = int(k)
    return f'{n} раза' if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14) else f'{n} раз'


def chg(k, verb=('увеличить', 'уменьшить')):
    """«увеличить в 2 раза» / «уменьшить в 3 раза»."""
    k = Fr(k)
    return f'{verb[0]} в {raz(k)}' if k > 1 else f'{verb[1]} в {raz(1 / k)}'


def ans_line(unit=None, sign=False, raz_=False):
    s = '\nПроекцию укажите с учётом её знака.' if sign else ''
    if raz_:
        return s + '\n\nОтвет: в ___ раз(а).'
    return s + (f'\n\nОтвет: ___ {unit}.' if unit else '\n\nОтвет: ___.')


