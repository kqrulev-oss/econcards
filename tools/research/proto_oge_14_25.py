def _triple(r, maxk=6, big=True, cmax=100):
    for _ in range(50):
        a, b, c = r.choice(TRIPLES[:10] if big else TRIPLES[:5])
        k = r.randint(1, maxk)
        if c * k <= cmax:
            break
    if r.random() < 0.5:
        a, b = b, a
    return a * k, b * k, c * k


