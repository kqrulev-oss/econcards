def rt(k, m=1):
    """k·√m текстом: rt(3, 2) → '3√2', rt(1, 3) → '√3'."""
    if m == 1:
        return tnum(k)
    return ('' if k == 1 else tnum(k)) + f'√{m}'


def ordm(n):
    """Порядковое с наращением в мужском/среднем роде, предложный падеж: 17-м."""
    return f'{n}-м'


def dist(P, Q):
    return math.hypot(P[0] - Q[0], P[1] - Q[1])


def ang(P, V, Q):
    """Угол PVQ в градусах (float)."""
    a = math.atan2(P[1] - V[1], P[0] - V[0])
    b = math.atan2(Q[1] - V[1], Q[0] - V[0])
    d = abs(math.degrees(a - b)) % 360
    return 360 - d if d > 180 else d


def area(pts):
    s = 0.0
    for i in range(len(pts)):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % len(pts)]
        s += x1 * y2 - x2 * y1
    return abs(s) / 2


def close(a, b, eps=1e-6):
    return abs(float(a) - float(b)) < eps


def tri_by_angles(A, B, c=10.0):
    """Треугольник с углами A и B (в градусах) при вершинах P0=(0,0), P1=(c,0)."""
    ra, rb = math.radians(A), math.radians(B)
    rc = math.pi - ra - rb
    b = c * math.sin(rb) / math.sin(rc)
    return (0.0, 0.0), (c, 0.0), (b * math.cos(ra), b * math.sin(ra))


