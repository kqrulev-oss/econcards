def _poll_statements(p):
    opts, pa, pb, ga, gb = p['opts'], p['pa'], p['pb'], p['ga'], p['gb']
    st = []
    for i, o in enumerate(opts):
        st.append((f'Доля выбравших вариант «{o}» среди {ga} больше, чем среди {gb}', ['gt', i], pa[i] > pb[i]))
        st.append((f'Доля выбравших вариант «{o}» среди {gb} больше, чем среди {ga}', ['lt', i], pb[i] > pa[i]))
        st.append((f'Вариант «{o}» — самый популярный в обеих группах опрошенных', ['top', i], pa[i] == max(pa) and pb[i] == max(pb)))
    for i, o in enumerate(opts):
        for j, o2 in enumerate(opts):
            if i != j:
                st.append((f'Среди {ga} вариант «{o}» выбрали больше опрошенных, чем вариант «{o2}»', ['a', i, j], pa[i] > pa[j]))
                st.append((f'Среди {gb} вариант «{o}» выбрали меньше опрошенных, чем вариант «{o2}»', ['b', i, j], pb[i] < pb[j]))
    return st


def _poll_eval(code, p):
    pa, pb = p['pa'], p['pb']
    if code[0] == 'gt':
        return pa[code[1]] > pb[code[1]]
    if code[0] == 'lt':
        return pb[code[1]] > pa[code[1]]
    if code[0] == 'top':
        return pa[code[1]] >= max(pa) and pb[code[1]] >= max(pb)
    if code[0] == 'a':
        return pa[code[1]] > pa[code[2]]
    return pb[code[1]] < pb[code[2]]


