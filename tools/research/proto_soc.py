def make_statements(rng, g, with_ages=False):
    """Список (текст, верно?, опора). Верные — из словаря, неверные — подменой признака соседнего понятия."""
    out = []
    for it in g['items']:
        for f in it['feats']:
            out.append((statement(g, it, f), True, g['basis']))
        for other in g['items']:
            if other is it:
                continue
            for f in other['feats']:
                out.append((statement(g, it, f), False, f'{g["basis"]}: признак понятия «{other["name"]}»'))
        for c in g['common']:
            out.append((statement(g, it, c), True, g['basis']))
    if with_ages:
        for row in AGES:
            out.append((age_statement(row, row[1]), True, row[3]))
            for w in row[4]:
                out.append((age_statement(row, w), False, f'{row[3]}: верно {row[1]}'))
    rng.shuffle(out)
    return out


def truth_of(text, g):
    """Независимая проверка суждения: разбор по словарю (какое понятие названо, чей признак)."""
    for row in AGES:
        m = re.fullmatch(re.escape(row[0]).replace(r'\{n\}', r'(\d+) [^,]+?'), text)
        if m:
            return int(m.group(1)) == row[1]
    for it in g['items']:
        for f in it['feats'] + g['common']:
            if statement(g, it, f) == text:
                return True
        for other in g['items']:
            if other is not it:
                for f in other['feats']:
                    if statement(g, it, f) == text:
                        return False
    return None


