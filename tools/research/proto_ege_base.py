def T(x):
    """Число в условии: типографский минус, тысячи разделены пробелом (17 500), как в КИМ."""
    s = tnum(x)
    neg = s.startswith('−')
    s = s.lstrip('−')
    whole, _, frac = s.partition(',')
    if len(whole) > 4:
        whole = f'{int(whole):,}'.replace(',', NB)
    return ('−' if neg else '') + whole + (',' + frac if frac else '')


def pl(n, one, few, many):
    """«21 рубль», «3 рубля», «17 500 рублей»; для дробных — родительный падеж ед. ч. («2,5 литра»)."""
    x = F(n)
    if x.denominator != 1:
        return f'{T(x)} {few}'
    return f'{T(x)} {plural(int(x), one, few, many)}'


def rub(n):
    """Сумма денег: «250 рублей», «116 руб. 20 коп.»."""
    x = F(n)
    if x.denominator == 1:
        return pl(x, 'рубль', 'рубля', 'рублей')
    kop = int(x * 100) % 100
    return f'{T(int(x))} руб. {kop:02d} коп.'


def ceil(a, b=1):
    """Округление вверх для дробей: ceil(7, 3) = 3."""
    q = F(a) / F(b)
    return -((-q.numerator) // q.denominator)


def floor(a, b=1):
    q = F(a) / F(b)
    return q.numerator // q.denominator


def dec(x):
    """Десятичная дробь в условии (без группировки тысяч)."""
    return tnum(x)


