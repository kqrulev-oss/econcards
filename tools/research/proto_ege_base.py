def ordw(k, case='nom_m'):
    """Порядковые числительные 1–12: ordw(3) → «третий», ordw(3, 'prep_m') → «третьем»."""
    base = ['', 'перв', 'втор', 'трет', 'четвёрт', 'пят', 'шест', 'седьм', 'восьм', 'девят', 'десят', 'одиннадцат',
            'двенадцат']
    b = base[k]
    if k == 3:
        return {'nom_m': 'третий', 'nom_f': 'третья', 'nom_n': 'третье', 'prep_m': 'третьем', 'gen_m': 'третьего',
                'acc_f': 'третью'}[case]
    hard = k in (2, 6, 7, 8)
    ends = {'nom_m': 'ой' if hard else 'ый', 'nom_f': 'ая', 'nom_n': 'ое', 'prep_m': 'ом', 'gen_m': 'ого', 'acc_f': 'ую'}
    return b + ends[case]


