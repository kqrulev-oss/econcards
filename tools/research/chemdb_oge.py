def _sign(prods, dissolve=False, colour_cat=None):
    tags = []
    for f in prods:
        if f in ('CO2', 'SO2', 'H2S', 'NH3'):
            tags.append('газ:' + f)
        elif f == 'H2SiO3' or f in _PRECIP_F:
            tags.append('осадок:' + f)
    if dissolve:
        tags.append('растворение')
        if colour_cat in SOLN_COLOR:
            tags.append('раствор:' + SOLN_COLOR[colour_cat])
    return '; '.join(tags) or 'нет'


_PRECIP_F = {_salt_formula(c, a) for (c, a), v in SOL.items() if v == 'н' and c != 'H' and a != 'OH'} | \
            {f for f, c in _INS_BASE.items()}


def _rx(lhs, rhs, typ, sign, cond='р-р'):
    return dict(lhs=list(lhs), rhs=list(rhs), type=list(typ), cond=cond, sign=sign,
                src='таблица растворимости (школьный курс)')


def _exchange_rows():
    rows = []
    salts = {(c, a): _salt_formula(c, a) for (c, a), v in SOL.items() if c != 'H' and a != 'OH' and v in ('р', 'м', 'н')}
    sol_salts = {k: f for k, f in salts.items() if SOL[k] == 'р'}
    # кислота + основание (нейтрализация)
    for acid, an in _ACIDS_ALL.items():
        for base, cat in list(_ALKALI.items()) + list(_INS_BASE.items()):
            if (acid, cat) in _REDOX_SKIP or not _salt_ok(cat, an):
                continue
            if base in _INS_BASE and acid in ('H3PO4', 'H2S', 'H2SiO3'):
                continue
            if acid in ('H2S', 'H2SiO3') and cat not in ('Li', 'Na', 'K'):
                continue
            salt = salts[(cat, an)]
            if SOL[(cat, an)] == 'м':
                continue
            sign = _sign([salt], dissolve=base in _INS_BASE, colour_cat=cat if SOL[(cat, an)] == 'р' else None)
            rows.append(_rx([base, acid], [salt, 'H2O'], ['обмена', 'нейтрализации'], sign))
    # кислота + основный/амфотерный оксид
    for acid, an in _STRONG.items():
        for ox, cat in _B_OXIDES.items():
            if (acid, cat) in _REDOX_SKIP or not _salt_ok(cat, an) or SOL[(cat, an)] == 'м':
                continue
            salt = salts[(cat, an)]
            rows.append(_rx([ox, acid], [salt, 'H2O'], ['обмена'],
                            _sign([salt], dissolve=True, colour_cat=cat if SOL[(cat, an)] == 'р' else None), cond=''))
    for ox in ('Na2O', 'K2O', 'CaO', 'BaO', 'MgO'):
        cat = _B_OXIDES[ox]
        rows.append(_rx([ox, 'H3PO4'], [salts[(cat, 'PO4')], 'H2O'], ['обмена'], _sign([salts[(cat, 'PO4')]], True), cond=''))
    # щёлочь + кислотный оксид
    for base, cat in _ALKALI.items():
        for ox, an in _A_OXIDES.items():
            if not _salt_ok(cat, an) or SOL[(cat, an)] == 'м':
                continue
            salt = salts[(cat, an)]
            rows.append(_rx([base, ox], [salt, 'H2O'], [], _sign([salt]), cond=''))
    # кислота + соль
    for acid, an in _ACIDS_ALL.items():
        if acid in ('H2S', 'H2SiO3'):
            continue
        for (c, a), salt in salts.items():
            if a == an or (acid, a) in _REDOX_SKIP or (acid, c) in _REDOX_SKIP:
                continue
            insoluble = SOL[(c, a)] != 'р'
            if acid == 'H3PO4' and (insoluble or a not in _GAS_ACID):
                continue
            if not _salt_ok(c, an):
                continue
            new_salt = salts[(c, an)]
            if insoluble:  # растворение нерастворимой соли слабой/летучей кислоты
                if a not in _GAS_ACID or SOL[(c, an)] != 'р' or (a == 'S' and c in ('Cu', 'Ag')) or c == 'Ag':
                    continue
                prods = [new_salt] + _GAS_ACID[a]
                rows.append(_rx([salt, acid], prods, ['обмена'],
                                _sign(prods, dissolve=True, colour_cat=c), cond=''))
                continue
            if a in _GAS_ACID or a == 'SiO3':
                if SOL[(c, an)] == 'м':
                    continue
                prods = [new_salt] + (_GAS_ACID[a] if a in _GAS_ACID else ['H2SiO3'])
                rows.append(_rx([salt, acid], prods, ['обмена'], _sign(prods)))
            elif SOL[(c, an)] == 'н':
                prods = [new_salt, acid_of(a)]
                rows.append(_rx([salt, acid], prods, ['обмена'], _sign(prods)))
    # щёлочь + соль
    for base, cat in _ALKALI.items():
        for (c, a), salt in sol_salts.items():
            if c == cat:
                continue
            p_salt_k = (cat, a)
            if not _salt_ok(*p_salt_k):
                continue
            p_salt = salts[p_salt_k]
            if c == 'NH4':
                if SOL[p_salt_k] == 'м':
                    continue
                prods = [p_salt, 'NH3', 'H2O']
                rows.append(_rx([salt, base], prods, ['обмена'], _sign(prods), cond='t'))
                continue
            b_sol = SOL.get((c, 'OH'))
            if b_sol in ('-', '?', 'м') or SOL[p_salt_k] == 'м':
                continue
            if b_sol == 'н' or SOL[p_salt_k] == 'н':
                p_base = [f for f, k in list(_INS_BASE.items()) + list(_ALKALI.items()) if k == c][0]
                prods = [p_base, p_salt]
                rows.append(_rx([salt, base], prods, ['обмена'], _sign(prods)))
    # соль + соль
    keys = sorted(sol_salts)
    for i, (c1, a1) in enumerate(keys):
        for (c2, a2) in keys[i + 1:]:
            if c1 == c2 or a1 == a2:
                continue
            if {c1, c2} & {'Fe3'} and {a1, a2} & {'I', 'S', 'SO3'}:
                continue
            if {c1, c2} == {'Ag', 'Fe2'}:
                continue
            p1, p2 = (c1, a2), (c2, a1)
            if not (_salt_ok(*p1) and _salt_ok(*p2)):
                continue
            s1, s2 = SOL[p1], SOL[p2]
            if 'м' in (s1, s2) or 'н' not in (s1, s2):
                continue
            prods = [salts[p1], salts[p2]]
            rows.append(_rx([sol_salts[(c1, a1)], sol_salts[(c2, a2)]], prods, ['обмена'], _sign(prods)))
    return rows


def acid_of(an):
    return ANIONS[an][3]


REACTIONS += _exchange_rows()

