def _parse_rx(text):
    out = []
    for line in text.strip().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('|')]
        eq = parts[0]
        typ = [t.strip() for t in parts[1].split(',')] if len(parts) > 1 and parts[1] else []
        cond = parts[2] if len(parts) > 2 else ''
        sign = parts[3] if len(parts) > 3 else ''
        lhs, rhs = eq.split('=')
        out.append(dict(lhs=[x.strip() for x in lhs.split(' + ')], rhs=[x.strip() for x in rhs.split(' + ')],
                        type=typ, cond=cond, sign=sign, src='школьный курс химии 8–9 кл.'))
    return out


