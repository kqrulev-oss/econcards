def _salt_formula(cat, an):
    cf, cq, _, _ = CATIONS[cat]
    af, aq, _, _, _ = ANIONS[an]
    from math import gcd
    g = gcd(cq, aq)
    nc, na = aq // g, cq // g
    poly_c = len([ch for ch in cf if ch.isupper()]) > 1
    poly_a = len([ch for ch in af if ch.isupper()]) > 1 or any(ch.isdigit() for ch in af)
    c = (f'({cf}){nc}' if poly_c else f'{cf}{nc}') if nc > 1 else cf
    a = (f'({af}){na}' if poly_a else f'{af}{na}') if na > 1 else af
    return c + a


def _salt_name(cat, an):
    return f'{ANIONS[an][2]} {CATIONS[cat][2]}'


