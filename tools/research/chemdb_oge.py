def _salt_rows():
    rows = []
    for (cat, an), v in SOL.items():
        if cat == 'H' or an == 'OH' or v not in ('р', 'м', 'н'):
            continue
        f = _salt_formula(cat, an)
        d = _s(f, _salt_name(cat, an), 'соль', 'средняя', sol=v, ion=[cat, an], strength='сильный')
        col = PRECIP_COLOR.get(f)
        if v == 'н' and col:
            d['color'] = col
        elif v != 'н' and cat in SOLN_COLOR:
            d['color'] = SOLN_COLOR[cat] + ' раствор'
        rows.append(d)
    return rows


