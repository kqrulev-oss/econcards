    t = sp.Symbol('t', nonnegative=True)

    def chk():
        d = sp.sqrt((a - v1 * t) ** 2 + (b - v2 * t) ** 2)
        crit = [c for c in sp.solve(sp.diff(d, t), t) if c >= 0]
        if len(crit) != 1:
            return False
        c = crit[0]
        return d.subs(t, c) < d.subs(t, 0) and same(num(ans), d.subs(t, c) if ask == 'd' else 60 * c)
    return pcard(q, num(ans), e), chk


