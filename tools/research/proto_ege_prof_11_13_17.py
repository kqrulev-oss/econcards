def yrs(n):
    return f'{n} {plural(n, "год", "года", "лет")}'


def cond(*items):
    """Список условий через тире, последний пункт — с точкой."""
    items = [i for i in items if i]
    heads = ['Условия кредита такие:', 'Банк выдаёт кредит на следующих условиях:', 'Порядок погашения такой:']
    h = heads[sum(map(ord, ''.join(items))) % 3]
    return h + '\n' + '\n'.join(f'— {t}{";" if i < len(items) - 1 else "."}' for i, t in enumerate(items))


def base_year(r):
    return r.randint(2027, 2032)


def g_annuity(k, n):
    """Доля платежа от кредита при n равных ежегодных платежах: X = S·kⁿ(k − 1)/(kⁿ − 1)."""
    return k ** n * (k - 1) / (k ** n - 1)


def sim_annuity(S, r, n):
    """Проверка: X из условия «долг после n лет равен нулю» (sympy, по годам)."""
    Xs = sp.Symbol('Xs')
    d = R(S)
    for _ in range(n):
        d = d * sp.Rational(100 + r, 100) - Xs
    return sp.solve(sp.Eq(d, 0), Xs)[0]


def annuity_numbers(r, rates=(10, 20, 20, 25, 30), ns=(2, 3, 3, 4), lo=100_000, hi=3_000_000):
    """Числа как в демоверсии 2027 (182 000 ₽, 20 %, 3 года ⇒ платёж 86 400 ₽): платёж круглый (кратен 100,
    в крайнем случае 10), кредит — до нескольких миллионов."""
    rate = r.choice(rates)
    n = r.choice(ns)
    k = F(100 + rate, 100)
    g = g_annuity(k, n)
    num_, den = g.numerator, g.denominator
    ms = [m for m in range(max(1, -(-lo // den)), hi // den + 1) if (num_ * m) % 100 == 0 and (den * m) % 10 == 0]
    if not ms:
        ms = [m for m in range(max(1, -(-lo // den)), hi // den + 1) if (num_ * m) % 10 == 0]
    if not ms:
        return None
    m = r.choice(ms)
    S = den * m
    X = S * g
    assert X.denominator == 1
    return rate, n, S, int(X)


