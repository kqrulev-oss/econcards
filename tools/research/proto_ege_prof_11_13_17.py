@proto('ep11-work-joint', 'ege-prof', 11, 'Совместная работа двух участников',
       invariant='Производительности складываются: 1/T = 1/a + 1/b; по двум из трёх времён найти третье.',
       varies='Сюжет (переводчики, экскаваторы, трубы, снегоуборщики, мастер и ученик), времена, что ищется.',
       answer_rule='T = ab/(a + b) или b = aT/(a − T).',
       fipi=r'один мастер может выполнить',
       mistakes=['складывают времена вместо производительностей', 'берут среднее арифметическое времён'],
       kim=kim(K11, 'Задача на совместную работу, вопрос «За сколько часов (дней) …?», ответ — число.'))
def gen_ep11_work_joint(r):
    s = r.choice(JOINT)
    a, b = r.randint(4, 60), r.randint(4, 60)
    if a == b:
        return None
    T = F(a * b, a + b)
    if not nice(T, 1):
        return None
    fmt = days if s['unit'] == 'd' else hours
    if r.random() < 0.55:
        q = f'{s["a"].format(a=fmt(a))}, {s["b"].format(b=fmt(b))}. {s["both"]}'
        ans, chk = T, lambda: one_root(sp.Eq(1 / V, sp.Rational(1, a) + sp.Rational(1, b)), V, T)
    else:
        q = f'{s["rev"].format(T=fmt(T), a=fmt(a))} {s["revq"]}'
        ans, chk = F(b), lambda: one_root(sp.Eq(1 / R(T), sp.Rational(1, a) + 1 / V), V, b)
    e = f'1/{a} + 1/{b} = 1/T ⇒ T = {tnum(T)}.'
    return pcard(q, num(ans), e), chk


def _triples():
    out = []
    ok = lambda p, q: (10 * p) % q == 0          # p/q записывается с одним знаком после запятой
    for a in range(2, 61):
        for b in range(a + 1, 91):
            if not ok(a * b, a + b):
                continue
            for c in range(b + 1, 121):
                if ok(b * c, b + c) and ok(a * c, a + c) and ok(a * b * c, a * b + b * c + a * c):
                    out.append((a, b, c))
    return out


