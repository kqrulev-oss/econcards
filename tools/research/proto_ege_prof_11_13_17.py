# ---------- движение: одинаковый путь, скорости отличаются на d, время — на t
# S/v − S/(v + d) = t  ⇔  v(v + d)·t = S·d


def speed_pair(r, vlo, vhi, dchoices, tchoices, slo, shi):
    v = r.randint(vlo, vhi)
    d = r.choice(dchoices)
    t = F(r.choice(tchoices))
    S = F(v * (v + d)) * t / d
    if S.denominator != 1 or not slo <= S <= shi:
        return None
    return v, d, t, int(S)


