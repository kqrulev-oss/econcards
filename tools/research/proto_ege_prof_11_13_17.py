def _boxes():
    out = []
    for a in range(6, 121, 2):
        for b in range(a, 121, 2):
            d = a * a - a * b + b * b
            s = math.isqrt(d)
            if s * s != d:
                continue
            x = F(a + b - s, 6)
            if finite(x) and 0 < x < F(a, 2):
                V = x * (a - 2 * x) * (b - 2 * x)
                if nice(V, 2, 10 ** 7):
                    out.append((a, b, x, V))
    return out


