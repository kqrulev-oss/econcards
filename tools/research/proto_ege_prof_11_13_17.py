def sim_diff(S, rate, debts):
    """Платежи по графику долгов (на июль/15-е число): pᵢ = Dᵢ₋₁·k − Dᵢ. Возвращает список (sympy)."""
    k = 1 + R(rate) / 100
    ds = [R(S)] + [R(d) for d in debts]
    return [ds[i - 1] * k - ds[i] for i in range(1, len(ds))]


