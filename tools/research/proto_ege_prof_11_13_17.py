ORD = ['На первом участке', 'на втором', 'на третьем']


def seg_phrase(i, t, v, verb, by_time):
    """«На первом участке он ехал 2 часа, держа скорость 60 км/ч» / «… длиной 120 км при скорости 60 км/ч»."""
    lead = ORD[i] if i else ORD[0]
    speed = pick_seg(i, v)
    if by_time:
        return f'{lead} {"он " if i == 0 else ""}{verb} {hours(t)} {speed}' if i == 0 else f'{lead} — {hours(t)} {speed}'
    lead = ['Первый участок', 'второй', 'третий'][i]
    return f'{lead} длиной {t} км {verb} {speed}' if i == 0 else f'{lead}, длиной {t} км, — {speed}'


def pick_seg(i, v):
    return [f'при скорости {v} км/ч', f'с постоянной скоростью {v} км/ч', f'при скорости {v} км/ч'][i]


