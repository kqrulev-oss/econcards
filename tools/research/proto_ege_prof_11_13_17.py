def label(sx, sy, x, y, t, dx=6, dy=-6):
    return (f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="3.5" fill="{INK}"/>'
            f'<text x="{sx(x) + dx:.1f}" y="{sy(y) + dy:.1f}" font-size="14" font-style="italic" font-weight="bold">{t}</text>')


def dashed(sx, sy, win, x0=None, y0=None):
    """Пунктирная асимптота в пределах окна win = (x0, x1, y0, y1)."""
    if x0 is not None:
        return (f'<line x1="{sx(x0):.1f}" y1="{sy(win[2]):.1f}" x2="{sx(x0):.1f}" y2="{sy(win[3]):.1f}" stroke="{INK}" '
                'stroke-width="1.2" stroke-dasharray="5 4"/>')
    return (f'<line x1="{sx(win[0]):.1f}" y1="{sy(y0):.1f}" x2="{sx(win[1]):.1f}" y2="{sy(y0):.1f}" stroke="{INK}" '
            'stroke-width="1.2" stroke-dasharray="5 4"/>')


def window(pts, xr=(-6, 6), ymin=8):
    """Окно рисунка по отмеченным точкам: x — фиксированный диапазон, y — с запасом в клетку."""
    ys = [p[1] for p in pts] + [0]
    y0, y1 = math.floor(min(ys)) - 1, math.ceil(max(ys)) + 1
    while y1 - y0 < ymin:
        if y1 - y0 < ymin:
            y1 += 1
        if y1 - y0 < ymin:
            y0 -= 1
    return xr[0], xr[1], y0, y1


def plot(fns, pts, extra=None, xr=(-6, 6), ymin=8, marks=()):
    """extra(sx, sy, win) — дорисовка (асимптоты, подписи); marks — точки, которые должны попасть в окно."""
    x0, x1, y0, y1 = window(list(pts) + list(marks), xr, ymin)
    if y1 - y0 > 14:
        return None
    win = (x0, x1, y0, y1)
    return svg_plot(fns, x0, x1, y0, y1, extra=(lambda sx, sy: extra(sx, sy, win)) if extra else None, points=pts)


