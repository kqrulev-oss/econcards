    txt, qq, unit = r.choice(THREE)
    fmt = days if unit == 'd' else hours
    t12, t23, t13 = F(a * b, a + b), F(b * c, b + c), F(a * c, a + c)
    if any(fmt(t) is None for t in (t12, t23, t13)):
        return None
    T = F(a * b * c, a * b + b * c + a * c)
    q = txt.format(t12=fmt(t12), t23=fmt(t23), t13=fmt(t13)) + ' ' + qq
