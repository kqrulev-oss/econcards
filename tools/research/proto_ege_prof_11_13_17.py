def sim_2eq(S, rate):
    """Два равных платежа X гасят долг S: (S·k − X)·k − X = 0."""
    Xs = sp.Symbol('Xs')
    k = sp.Rational(100 + rate, 100)
    return sp.solve(sp.Eq((R(S) * k - Xs) * k - Xs, 0), Xs)[0]


