def _triples():
    out = []
    ok = lambda p, q: (10 * p) % q == 0          # p/q записывается с одним знаком после запятой
    for a in range(2, 61):
        for b in range(a + 1, 91):
            if not ok(a * b, a + b):
                continue
            for c in range(b + 1, 121):
                if ok(b * c, b + c) and ok(a * c, a + c) and ok(a * b * c, a * b + b * c + a * c):
                    out.append((a, b, c))
    return out


