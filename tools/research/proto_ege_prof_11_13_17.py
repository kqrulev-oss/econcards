    if max(v1, v2) > 30 and r.random() < 0.3:
        return None
    txt, who = r.choice(MOTION_STORY)
    lo, hi = (1, 40) if 'автомоб' in txt else ((1, 20) if 'катер' in txt else (1, 10))
    if ('велосип' in txt and max(v1, v2) > 25) or ('катер' in txt and max(v1, v2) > 60) or ('автомоб' in txt and min(v1, v2) < 30):
        return None
    a, b = r.randint(lo, hi), r.randint(lo, hi)
    w2 = v1 * v1 + v2 * v2
    w = math.isqrt(w2)
    tmin = F(a * v1 + b * v2, w2) * 60          # минуты
    dmin = F(abs(a * v2 - b * v1), w)
    if dmin == 0 or not nice(tmin, 1) or not nice(dmin, 2) or tmin < 2:
        return None
    ask = r.choice(['d', 't'])
    q = txt.format(v1=v1, v2=v2, a=a, b=b) + ' ' + (
        f'Найдите наименьшее расстояние между {who}. Ответ дайте в километрах.' if ask == 'd' else
        f'Через сколько минут после начала движения расстояние между {who} будет наименьшим?')
