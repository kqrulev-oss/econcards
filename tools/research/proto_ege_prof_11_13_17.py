@proto('ep12-log-shift', 'ege-prof', 12, 'Сдвинутая логарифмическая функция по графику: значение в точке',
       invariant='logₐ(x + b) — сдвиг по оси x (асимптота x = −b); logₐx + b — сдвиг по оси y; параметры читаются по узлам.',
       varies='Вид сдвига, основание, сдвиг, точка вычисления.',
       answer_rule='По асимптоте или узлу (1; b) находим сдвиг, по второму узлу — основание.',
       fipi=r'log a \( x \+ b \)|b \+ log a x',
       mistakes=['путают направление сдвига', 'теряют сдвиг при вычислении'],
       svg=True, kim=kim(K12, 'Рисунок на клетке, «Найдите значение f(…)».', kes=['3.5']))
def gen_ep12_log_shift(r):
    a = r.choice([2, 3, F(1, 2), F(1, 3)])
    b = r.choice([-3, -2, -1, 1, 2, 3])
    horiz = r.random() < 0.5
    if horiz:
        nodes = log_nodes(a, shift=b)
        form, fn = 'f(x) = logₐ(x + b)', (lambda x: math.log(x + b, float(a)) if x + b > 0 else None)
        extra = lambda sx, sy, w: dashed(sx, sy, w, x0=-b)
    else:
        nodes = log_nodes(a, add=b)
        form, fn = 'f(x) = logₐx + b', (lambda x: math.log(x, float(a)) + b if x > 0 else None)
        extra = None
    nodes = [n for n in nodes if abs(n[1]) <= 6]
    if len(nodes) < 2:
        return None
    m = r.randint(-3, 6)
    x0 = F(a) ** m - (b if horiz else 0)
    ans = m + (0 if horiz else b)
    if not nice(x0, 3) or x0 > 2000 or any(n[0] == x0 for n in nodes):
        return None
    svg = plot(fn, nodes, extra=extra, xr=(-4, 10))
    if not svg:
        return None
    q = r.choice(ASK_V).format(F=form, Q=fx(x0))
    e = f'a = {fr(a)}, b = {tnum(b)}; f({tnum(x0)}) = {tnum(ans)}.'
    aa, bb = sp.symbols('aa bb', real=True)

    def chk():
        (p1, q1), (p2, q2) = nodes[:2]
        if horiz:
            s = sp.solve([sp.Eq(aa ** q1, p1 + bb), sp.Eq(aa ** q2, p2 + bb)], [aa, bb], dict=True)
            s = [t for t in s if t[aa].is_positive and t[aa] != 1]
            return len(s) == 1 and same(num(ans), sp.log(R(x0) + s[0][bb]) / sp.log(s[0][aa]))
        bv = q1 - sp.log(p1) / sp.log(R(a))
        return sp.simplify(sp.log(p2) / sp.log(R(a)) + bv - q2) == 0 and same(num(ans), sp.log(R(x0)) / sp.log(R(a)) + bv)
    return pcard(q, num(ans), e, svg=svg), chk


@proto('ep12-trig', 'ege-prof', 12, 'Тригонометрическая функция по графику: значение в точке',
       invariant='a·sin(bπx) + c (или cos): c — средняя линия, |a| — амплитуда, b — по периоду; знак a — по поведению в нуле.',
       varies='sin или cos, амплитуда, сдвиг, период (2, 4, 8), точка вычисления (далеко за рисунком или дробная).',
       answer_rule='Находим a, b, c по узлам (максимум, минимум, пересечение средней линии), затем подставляем x₀.',
       fipi=r'a (sin|cos) .*x \+ b',
       mistakes=['путают амплитуду и размах', 'ошибаются с периодом', 'теряют знак a'],
       svg=True, kim=kim(K12, 'Рисунок на клетке, «Найдите значение f(…)».', kes=['3.4', '3.1']))
def gen_ep12_trig(r):
    kind = r.choice(['sin', 'cos'])
    a = r.choice([-3, -2, -1, 1, 2, 3])
    c = r.choice([-2, -1, 0, 1, 2])
    b = r.choice([F(1, 2), F(1, 4), F(1, 1)])
    if abs(a) + abs(c) > 5:
        return None
    T = 2 / b
    trig = math.sin if kind == 'sin' else math.cos

    def val(x):                     # точное значение в точках, где bπx кратно π/6
        t = F(x) * b * 6            # аргумент в единицах π/6
        if t.denominator != 1:
            return None
        s_tab = {0: 0, 1: F(1, 2), 3: 1, 5: F(1, 2), 6: 0, 7: F(-1, 2), 9: -1, 11: F(-1, 2)}
        k = int(t) % 12
        sv = s_tab.get(k)
        cv = s_tab.get((k + 3) % 12)
        v = sv if kind == 'sin' else cv
        return None if v is None else a * v + c
    nodes = [(x, val(x)) for x in range(-6, 7) if val(x) is not None and F(val(x)).denominator == 1]
    ext = [n for n in nodes if n[1] in (c + a, c - a)]
    if len(ext) < 2:
        return None
    x0 = r.choice([F(r.randint(10, 60) * r.choice([1, -1])), F(1, 3) / b + 2 * r.randint(0, 3) / b,
                   F(2, 3) / b + 2 * r.randint(1, 5) / b, F(1, 6) / b + T * r.randint(1, 4)])
    ans = val(x0)
    if ans is None or not nice(ans, 2) or (x0.denominator == 1 and -7 < x0 < 7) or not finite(x0) and x0.denominator > 6:
        return None
    fn = lambda x: a * trig(float(b) * math.pi * x) + c
    show = [n for n in nodes if n[1] in (c + a, c - a) or n[1] == c][:7]
    svg = plot(fn, show, ymin=7)
    if not svg:
        return None
    form = f'f(x) = a·{kind}(bπx) + c'
    q = r.choice(ASK_V).format(F=form, Q=fxq(x0))
    e = f'c = {tnum(c)}, a = {tnum(a)}, период {tnum(T)} ⇒ b = {fr(b)}; {fxq(x0)} = {tnum(ans)}.'
    fsym = (sp.sin if kind == 'sin' else sp.cos)
    return pcard(q, num(ans), e, svg=svg), lambda: same(num(ans), a * fsym(R(b) * sp.pi * R(x0)) + c) and \
        all(same(tnum(y).replace('−', '-'), a * fsym(R(b) * sp.pi * px) + c) for px, y in show)


