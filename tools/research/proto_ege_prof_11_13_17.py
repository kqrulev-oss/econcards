    walk = 'Турист' in txt
    m, n_, kk = r.choice([(3, 5, 4), (4, 5, 3), (5, 13, 12), (8, 17, 15), (12, 13, 5), (7, 25, 24)])
    if walk:
        V1, V2 = r.choice([(5, 3), (5, 4)])
        kk = math.isqrt(V1 * V1 - V2 * V2)                 # x/√(h² + x²) = V2/V1 ⇒ x = h·V2/kk
