def _dep(A, rate, n, adds):
    """Моделирование вклада по годам: в начале года j — пополнение, в конце — проценты."""
    s = F(A)
    for j in range(1, n + 1):
        s += adds.get(j, 0)
        s = s * F(100 + rate, 100)
    return s


