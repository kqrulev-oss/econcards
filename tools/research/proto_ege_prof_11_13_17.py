def fr(x):
    """Обыкновенная дробь в условии: 7/12, −3/4; целое — числом."""
    x = F(x)
    if x.denominator == 1:
        return tnum(x)
    return f'{"−" if x < 0 else ""}{abs(x.numerator)}/{x.denominator}'


def rub(x):
    """Сумма с разрядами: 182 000; 1 234 567; дробь — через запятую."""
    x = F(x)
    if x.denominator != 1:
        return tnum(x)
    s = str(abs(x.numerator))
    if len(s) > 4:
        g = []
        while s:
            g.insert(0, s[-3:])
            s = s[:-3]
        s = ' '.join(g)
    return ('−' if x < 0 else '') + s


def hours(t):
    """Промежуток времени: «3 часа», «1,5 часа», «40 минут», «2 часа 20 минут»."""
    t = F(t)
    if t.denominator == 1:
        n = int(t)
        return f'{n} {plural(n, "час", "часа", "часов")}'
    m = t * 60
    if m.denominator == 1 and t < 1:
        m = int(m)
        return f'{m} {plural(m, "минуту", "минуты", "минут")}'
    if finite(t) and t.denominator in (2, 4, 5, 10):
        return f'{tnum(t)} часа'
    if m.denominator == 1:
        h, mm = divmod(int(m), 60)
        return f'{h} {plural(h, "час", "часа", "часов")} {mm} {plural(mm, "минуту", "минуты", "минут")}'
    return None


def pos_roots(eq, var):
    """Положительные вещественные корни уравнения (для проверок)."""
    return [s for s in sp.solve(eq, var) if s.is_real and s > 0]


def one_root(eq, var, ans, cond=lambda s: True):
    """Проверка: ровно один подходящий по смыслу корень, и он равен ответу."""
    roots = [s for s in pos_roots(eq, var) if cond(s)]
    return len(roots) == 1 and same(num(ans), roots[0])


def pc(p):
    """Процент в условии: 12,5 %."""
    return f'{tnum(p)} %'


