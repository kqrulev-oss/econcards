def boat_trip(r, b, tmax=40):
    v = r.randint(*b['v'])
    u = r.randint(1, max(1, min(6, v // 4)))
    Tm = r.randint(2, tmax)
    S = F(Tm * (v * v - u * u), 2 * v)
    if S.denominator != 1 or S < 10:
        return None
    return v, u, int(S), Tm


def trip_text(r, b, S, stay, T):
    dirn = pick(r, 'вниз по течению', 'вверх по течению')
    went = 'прошёл' if b['m'] else 'прошла'
    came = 'вернулся' if b['m'] else 'вернулась'
