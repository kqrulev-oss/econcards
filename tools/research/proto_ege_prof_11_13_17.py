def line_through(r, k_lim=4):
    q_ = r.choice([1, 1, 2, 3])
    p_ = r.choice([i for i in range(-k_lim, k_lim + 1) if i and math.gcd(i, q_) == 1])
    x1 = r.randint(-5, 5 - q_)
    y1 = r.randint(-4, 4)
    x2, y2 = x1 + q_, y1 + p_
    if abs(y2) > 5:
        return None
    k = F(p_, q_)
    return k, y1 - k * x1, [(x1, y1), (x2, y2)]


