def parabola(r):
    a = r.choice([1, -1, 1, -1, 2, -2, F(1, 2), F(-1, 2)])
    h, m = r.randint(-3, 3), r.randint(-4, 4)
    f = lambda x: a * (x - h) ** 2 + m
    pts = [(h, m)] + [(h + d, f(h + d)) for d in (-2, -1, 1, 2) if F(f(h + d)).denominator == 1 and abs(f(h + d)) <= 6 and -6 < h + d < 6]
    if len(pts) < 3:
        return None
    b, c = -2 * a * h, a * h * h + m
    return a, F(b), F(c), f, pts


