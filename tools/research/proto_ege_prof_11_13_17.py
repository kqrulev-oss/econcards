@proto('ep11-move-race', 'ege-prof', 11, 'Движение: одновременный старт, один быстрее и приходит раньше',
       invariant='Путь одинаковый, скорости отличаются на d, время — на t: S/v − S/(v + d) = t, квадратное уравнение.',
       varies='Сюжет (автобусы, яхты, лыжники, курьеры, грузовики), путь, разности скоростей и времени, чья скорость.',
       answer_rule='v(v + d) = S·d/t, берём положительный корень; ответ — скорость нужного участника.',
       fipi=r'одновременно отправились в .*пробег',
       mistakes=['записывают разность времён в обратном порядке', 'дают скорость не того участника'],
       kim=kim(K11, 'Сюжетная задача на движение, вопрос «Найдите скорость …», «Ответ дайте в км/ч.»; числа как в банке.'))
def gen_ep11_move_race(r):
    s = r.choice(RACE)
    res = speed_pair(r, *s['v'], [1, 2, 3, 4, 5, 6, 8, 9, 10, 12, 15], [1, 2, 3, 4, 5, F(1, 2), F(3, 2), F(2, 3), F(4, 3)], *s['S'])
    if not res:
        return None
    v, d, t, S = res
    if 2 * d > v:
        return None
    fast = r.random() < 0.5
    ans = v + d if fast else v
    q = (s['start'].format(S=S) + ' ' +
         f'{s["one"]} со скоростью, на {d} км/ч большей, чем {s.get("oth", "другой")}, и {s["fin"]} на {hours(t)} раньше. '
         f'Найдите скорость {s["first"] if fast else s["last"]}. Ответ дайте в км/ч.')
    e = f'{S}/v − {S}/(v + {d}) = {fr(t)} ⇒ v = {v}; скорости {v} и {v + d} км/ч.'
    return pcard(q, num(ans), e), lambda: one_root(sp.Eq(S / V - S / (V + d), R(t)), V, v) and ans in (v, v + d)
