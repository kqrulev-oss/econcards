def diff_credit(S, r, n):
    """Долг уменьшается на S/n после каждого начисления r. Возвращает платежи."""
    debt, pays = S, []
    for _ in range(n):
        debt *= 1 + r
        pay = debt - (S - S / n * (len(pays) + 1))
        pays.append(pay)
        debt -= pay
    assert near(debt, 0, 1e-6)
    return pays


def annuity(S, r, n):
    k = 1 + r
    x = S * k ** n * (k - 1) / (k ** n - 1)
    debt = S
    for _ in range(n):
        debt = debt * k - x
    assert near(debt, 0, 1e-3)
    return x


