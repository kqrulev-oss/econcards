def near(x, y, eps=1e-6):
    return abs(x - y) < eps


def ans(a):
    return float(str(a).replace(',', '.'))


def check(card, value):
    """Ответ карточки (или «Ответ: …» в конце решения) совпадает с вычислением."""
    a = card['a'].rsplit('Ответ:', 1)[-1].strip().rstrip('.') if card['k'] == 'open' else card['a']
    assert near(ans(a), value), (card['q'][:60], a, value)
    return card


def roots_on(f, a, b, n=200000):
    """Все корни f на [a; b], включая точки касания оси (ищем нули |f|)."""
    h = (b - a) / n
    xs = [a + i * h for i in range(n + 1)]
    vs = [abs(f(x)) for x in xs]
    found = []
    for i in range(n + 1):
        left = vs[i - 1] if i > 0 else math.inf
        right = vs[i + 1] if i < n else math.inf
        if vs[i] <= left and vs[i] <= right and vs[i] < 1e-2:
            lo, hi = max(a, xs[i] - h), min(b, xs[i] + h)
            for _ in range(200):
                m1, m2 = lo + (hi - lo) / 3, hi - (hi - lo) / 3
                if abs(f(m1)) < abs(f(m2)):
                    hi = m2
                else:
                    lo = m1
            x = (lo + hi) / 2
            if abs(f(x)) < 1e-9 and not any(near(x, y, 1e-5) for y in found):
                found.append(x)
    return found


def pi_str(fr):
    fr = Fr(fr)
    if fr == 0:
        return '0'
    s = '−' if fr < 0 else ''
    n, d = abs(fr.numerator), fr.denominator
    return s + ('π' if n == 1 else f'{n}π') + (f'/{d}' if d != 1 else '')


def check_roots(f, seg, claimed):
    """claimed — корни в долях π; проверяем, что это ровно все корни на отрезке."""
    a, b = float(seg[0]) * PI, float(seg[1]) * PI
    got = sorted(roots_on(f, a, b))
    want = sorted(float(c) * PI for c in claimed)
    assert len(got) == len(want) and all(near(x, y, 1e-5) for x, y in zip(got, want)), (got, want)
    return ', '.join(pi_str(c) for c in sorted(claimed))


def extreme(f, a, b, kind, n=200000):
    vals = [f(a + (b - a) * i / n) for i in range(n + 1)]
    return max(vals) if kind == 'max' else min(vals)


def local_point(f, x, kind, h=1e-3):
    sgn = 1 if kind == 'max' else -1
    return sgn * (f(x) - f(x - h)) > 0 and sgn * (f(x) - f(x + h)) > 0


def solve_set(pred, lo=-50, hi=50, n=100000):
    return [pred(lo + (hi - lo) * i / n + 1e-7) for i in range(n + 1)]


def interval_pred(parts):
    """parts: [(a, b, a_incl, b_incl)] → предикат принадлежности."""
    def p(x):
        return any((a < x or (ai and x == a)) and (x < b or (bi and x == b)) for a, b, ai, bi in parts)
    return p


def same_set(pred, parts, lo=-50, hi=50):
    """Решение неравенства совпадает с объединением промежутков (сетка + концы)."""
    p = interval_pred(parts)
    for i in range(100001):
        x = lo + (hi - lo) * i / 100000 + 1.234e-6
        try:
            v = pred(x)
        except (ValueError, ZeroDivisionError):
            v = False
        if v != p(x):
            return False
    for a, b, ai, bi in parts:
        for x, incl in ((a, ai), (b, bi)):
            if math.isfinite(x):
                try:
                    v = pred(x)
                except (ValueError, ZeroDivisionError):
                    v = False
                if v != incl:
                    return False
    return True


