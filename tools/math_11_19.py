def dots(nodes, color='#15181E'):
    return lambda sx, sy: ''.join(f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="3.5" fill="{color}"/>' for x, y in nodes)


def graph(fns, win, nodes, asym=()):
    """fns[0] рисует _svg_plot, остальные функции и асимптоты — поверх."""
    x0, x1, y0, y1 = win
    for f, pts in zip(fns, nodes):
        for x, y in pts:
            assert near(f(x), y) and float(y).is_integer() and float(x).is_integer(), (x, y, f(x))

    def extra(sx, sy):
        out = ''
        for f in fns[1:]:
            out += f'<line x1="{sx(x0):.1f}" y1="{sy(f(x0)):.1f}" x2="{sx(x1):.1f}" y2="{sy(f(x1)):.1f}" stroke="#E4572E" stroke-width="2.4"/>'
        for kind, v in asym:
            if kind == 'x':
                out += f'<line x1="{sx(v):.1f}" y1="{sy(y0):.1f}" x2="{sx(v):.1f}" y2="{sy(y1):.1f}" stroke="#6A7180" stroke-dasharray="5 4"/>'
            else:
                out += f'<line x1="{sx(x0):.1f}" y1="{sy(v):.1f}" x2="{sx(x1):.1f}" y2="{sy(v):.1f}" stroke="#6A7180" stroke-dasharray="5 4"/>'
        for pts in nodes:
            out += dots(pts)(sx, sy)
        return out
    return _svg_plot(fns[0], x0, x1, y0, y1, extra)


def gcard(q, a, value, e, svg):
    c = num(q, a, value, e)
    c['svg'] = svg
    return c


