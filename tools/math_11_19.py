def real_roots(a, b, c):
    d = b * b - 4 * a * c
    if d < -1e-12:
        return []
    if abs(d) <= 1e-12:
        return [-b / (2 * a)]
    s = math.sqrt(d)
    return [(-b - s) / (2 * a), (-b + s) / (2 * a)]


