def to_blank(c):
    """Карточки истории и обществознания: варианты в тексте, ответ — цифры."""
    k, a = c['k'], c['a']
    if k in ('match', 'seq') and isinstance(a, str) and a.isdigit():
        return dict(c, k='seq', a=a)
    if k == 'many' and isinstance(a, str) and a.isdigit():
        return dict(c, k='seq', a=a, any=True)
    if k == 'one' and isinstance(a, str) and 'o' not in c:
        return dict(c, k='word', a=a)
    return c


def strip(c):
    return {k: v for k, v in c.items() if k in ('id', 'k', 'q', 'a', 'o', 'e', 'svg', 'any', 'tol', 'x')}


def bio_geo(spec, log):
    import gen_bio_geo as B
    _, data = B.load_protos(spec['src'])
    by_n = {}
    for p in data['prototypes']:
        if p['exam'] == spec['exam'] and not isinstance(p['gen'], dict):
            by_n.setdefault(p['n'], []).append(p)

    def make(p):
        r = B.run_proto(p, PER_PROTO * 4, seed=SEED)
        if r['bad'] or r['inval']:
            raise SystemExit(f'{p["id"]}: {len(r["bad"])} несошедшихся, {len(r["inval"])} невалидных')
        out = []
        for i, c in enumerate(r['cards'][:PER_PROTO], 1):
            c = strip(c)
            c['id'] = f'{p["id"]}-{i}'
            if c['k'] == 'num' and 'x' in c:      # последовательность цифр записана как число
                c['k'] = 'seq'
            c.pop('x', None)
            out.append(c)
        return out
    return assemble(spec, by_n, make, log)


def inf(spec, log):
    import proto_inf as I
    by_n = {}
    for p in I.PROTOS:
        if p['exam'] == spec['exam'] and p.get('gen'):
            by_n.setdefault(p['n'], []).append(p)

    def make(p):
        cards, bad, _, _ = I.sample_cards(p, random.Random(f'{SEED}-{p["id"]}'), PER_PROTO, PER_PROTO)
        if bad:
            raise SystemExit(f'{p["id"]}: {bad} несошедшихся ответов')
        out = []
        for i, c in enumerate(cards, 1):
            c = strip(c)
            c['id'] = f'{p["id"]}-{i}'
            out.append(c)
        return out
    return assemble(spec, by_n, make, log)


def social(spec, log):
    import gen_social as S
    by_n = {}
    for p in S.all_protos(spec['src']):
        if p['exam'] == spec['exam'] and p.get('_gen'):
            by_n.setdefault(p['n'], []).append(p)

    def make(p):
        cards, bad, _ = S.selfcheck(p, PER_PROTO, PER_PROTO * 30, SEED)
        good = [c for c in cards if '_mismatch' not in c]
        if len(good) < len(cards):
            log(f'  {p["id"]}: {len(cards) - len(good)} карточек не прошли пересчёт — отброшены')
        return [strip(to_blank(c)) for c in good]
    return assemble(spec, by_n, make, log)


def more_packs(log=print):
    out = []
    for spec in PACKS:
        build = bio_geo if spec['src'] in ('bio', 'geo') else inf if spec['src'] == 'inf' else social
        out.append(build(spec, log))
    return out


